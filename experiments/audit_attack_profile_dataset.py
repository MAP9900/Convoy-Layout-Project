"""Audit and summarize synthetic attack-profile datasets stored as JSONL."""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path
from statistics import mean
from typing import Any, Iterable, Mapping

from experiments.generate_attack_profile_scaffold import APPROACH_PRESETS, RANGE_PRESETS


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Audit a generated attack-profile JSONL dataset")
    parser.add_argument(
        "--input",
        type=Path,
        required=True,
        help="Path to dataset JSONL file generated by experiments.generate_attack_profile_scaffold --mode dataset",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/diag/attack_profile_dataset_audit"),
        help="Directory for summary JSON/CSV outputs",
    )
    return parser.parse_args()


def load_dataset_records(path: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as f:
        for line_number, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:  # pragma: no cover - defensive
                raise ValueError(f"Invalid JSON at line {line_number} in {path}") from exc
            if not {"profile", "audit", "generator_meta"} <= set(row):
                raise ValueError(f"Line {line_number} in {path} is missing required dataset keys")
            records.append(row)
    return records


def _extract_family_and_range(name: str) -> tuple[str, str]:
    prefix_removed = name
    for leader in ("dataset_", "profile_"):
        if prefix_removed.startswith(leader):
            parts = prefix_removed.split("_", 2)
            if len(parts) == 3:
                prefix_removed = parts[2]
            break
    for approach in APPROACH_PRESETS:
        for range_preset in RANGE_PRESETS:
            token = f"{approach.name}_{range_preset.name}_"
            if prefix_removed.startswith(token):
                return approach.name, range_preset.name
    return "unknown", "unknown"


def flatten_dataset_records(records: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for record in records:
        profile = dict(record["profile"])
        audit = dict(record["audit"])
        meta = dict(record["generator_meta"])
        intent = dict(record.get("intent", {}))
        approach_family, range_band = _extract_family_and_range(str(profile.get("name", "")))
        row = {
            "profile_id": str(profile["profile_id"]),
            "name": str(profile["name"]),
            "approach_family": approach_family,
            "range_band": range_band,
            "target_zone_id": str(intent.get("target_zone_id", audit.get("target_zone_id", ""))),
            "target_zone_kind": str(intent.get("target_zone_kind", audit.get("target_zone_kind", ""))),
            "approach_side": str(intent.get("approach_side", audit.get("approach_side", ""))),
            "approach_lane": str(intent.get("approach_lane", audit.get("approach_lane", ""))),
            "intended_label": str(intent.get("intended_label", audit.get("intended_label", ""))),
            "spawn_region": str(intent.get("spawn_region", audit.get("spawn_region", ""))),
            "inside_convoy_envelope": bool(
                intent.get("inside_convoy_envelope", audit.get("inside_convoy_envelope", False))
            ),
            "target_aspect_deg": float(intent.get("target_aspect_deg", audit.get("target_aspect_deg", 0.0))),
            "target_score": float(intent.get("target_score", audit.get("target_score", 0.0))),
            "nearest_ship_clearance_m": float(
                intent.get("nearest_ship_clearance_m", audit.get("nearest_ship_clearance_m", 0.0))
            ),
            "aim_solution_kind": str(intent.get("aim_solution_kind", audit.get("aim_solution_kind", ""))),
            "aim_intercept_time_s": float(intent.get("aim_intercept_time_s", audit.get("aim_intercept_time_s", 0.0))),
            "aim_lead_distance_m": float(intent.get("aim_lead_distance_m", audit.get("aim_lead_distance_m", 0.0))),
            "n": int(profile["n"]),
            "speed_mps": float(profile["speed"]),
            "base_bearing_rad": float(profile["base_bearing_rad"]),
            "spread_doctrine": str(profile["spread_doctrine"]),
            "spread_deg": float(audit["spread_deg"]),
            "launch_delay_s": float(profile["launch_delay_s"]),
            "salvo_interval_s": float(profile["salvo_interval_s"]),
            "u_boat_initial_speed_mps": float(profile["u_boat_initial_speed_mps"]),
            "u_pos_x": float(audit["u_pos_x"]),
            "u_pos_y": float(audit["u_pos_y"]),
            "range_to_centroid_m": float(audit["range_to_centroid_m"]),
            "range_to_target_m": float(audit.get("range_to_target_m", audit["range_to_centroid_m"])),
            "range_to_aim_m": float(audit.get("range_to_aim_m", audit.get("range_to_target_m", audit["range_to_centroid_m"]))),
            "bearing_error_deg": float(audit["bearing_error_deg"]),
            "target_bearing_error_deg": float(audit.get("target_bearing_error_deg", audit["bearing_error_deg"])),
            "severity": float(audit["severity"]),
            "flag_count": int(audit["flag_count"]),
            "suggested_label": str(audit["suggested_label"]),
            "flags": ";".join(str(flag) for flag in audit.get("flags", [])),
            "source": str(meta.get("source", "")),
            "generator_version": str(meta.get("generator_version", "")),
            "mode": str(meta.get("mode", "")),
            "seed": int(meta.get("seed", 0)),
            "convoy_profile": str(meta.get("convoy_profile", "")),
        }
        rows.append(row)
    return rows


def _count_mapping_rows(counts: Mapping[str, int]) -> list[dict[str, Any]]:
    return [{"value": key, "count": int(counts[key])} for key in sorted(counts)]


def summarize_flat_rows(rows: list[dict[str, Any]]) -> dict[str, Any]:
    if not rows:
        return {
            "profile_count": 0,
            "labels": {},
            "approach_families": {},
            "range_bands": {},
            "target_zone_kinds": {},
            "spawn_regions": {},
            "approach_sides": {},
            "approach_lanes": {},
            "spread_deg_values": {},
            "u_boat_speed_values_mps": {},
        }

    label_counter = Counter(str(row["suggested_label"]) for row in rows)
    approach_counter = Counter(str(row["approach_family"]) for row in rows)
    range_counter = Counter(str(row["range_band"]) for row in rows)
    target_zone_counter = Counter(str(row["target_zone_kind"]) for row in rows if str(row["target_zone_kind"]))
    spawn_region_counter = Counter(str(row["spawn_region"]) for row in rows if str(row["spawn_region"]))
    approach_side_counter = Counter(str(row["approach_side"]) for row in rows if str(row["approach_side"]))
    approach_lane_counter = Counter(str(row["approach_lane"]) for row in rows if str(row["approach_lane"]))
    spread_counter = Counter(f"{float(row['spread_deg']):.1f}" for row in rows)
    u_boat_speed_counter = Counter(f"{float(row['u_boat_initial_speed_mps']):.1f}" for row in rows)
    launch_delay_counter = Counter(f"{float(row['launch_delay_s']):.1f}" for row in rows)
    salvo_interval_counter = Counter(f"{float(row['salvo_interval_s']):.1f}" for row in rows)

    return {
        "profile_count": len(rows),
        "labels": dict(label_counter),
        "approach_families": dict(approach_counter),
        "range_bands": dict(range_counter),
        "target_zone_kinds": dict(target_zone_counter),
        "spawn_regions": dict(spawn_region_counter),
        "inside_convoy_envelope": {
            "true": int(sum(1 for row in rows if bool(row["inside_convoy_envelope"]))),
            "false": int(sum(1 for row in rows if not bool(row["inside_convoy_envelope"]))),
        },
        "approach_sides": dict(approach_side_counter),
        "approach_lanes": dict(approach_lane_counter),
        "spread_deg_values": dict(spread_counter),
        "u_boat_speed_values_mps": dict(u_boat_speed_counter),
        "launch_delay_values_s": dict(launch_delay_counter),
        "salvo_interval_values_s": dict(salvo_interval_counter),
        "bearing_error_deg": {
            "mean": float(mean(float(row["bearing_error_deg"]) for row in rows)),
            "min": float(min(float(row["bearing_error_deg"]) for row in rows)),
            "max": float(max(float(row["bearing_error_deg"]) for row in rows)),
        },
        "range_to_centroid_m": {
            "mean": float(mean(float(row["range_to_centroid_m"]) for row in rows)),
            "min": float(min(float(row["range_to_centroid_m"]) for row in rows)),
            "max": float(max(float(row["range_to_centroid_m"]) for row in rows)),
        },
        "range_to_target_m": {
            "mean": float(mean(float(row["range_to_target_m"]) for row in rows)),
            "min": float(min(float(row["range_to_target_m"]) for row in rows)),
            "max": float(max(float(row["range_to_target_m"]) for row in rows)),
        },
        "severity": {
            "mean": float(mean(float(row["severity"]) for row in rows)),
            "min": float(min(float(row["severity"]) for row in rows)),
            "max": float(max(float(row["severity"]) for row in rows)),
        },
        "top_10_highest_severity": [
            {
                "profile_id": row["profile_id"],
                "name": row["name"],
                "severity": row["severity"],
                "bearing_error_deg": row["bearing_error_deg"],
                "suggested_label": row["suggested_label"],
                "approach_family": row["approach_family"],
                "range_band": row["range_band"],
                "target_zone_kind": row["target_zone_kind"],
                "spawn_region": row["spawn_region"],
                "approach_side": row["approach_side"],
            }
            for row in sorted(rows, key=lambda item: float(item["severity"]), reverse=True)[:10]
        ],
    }


def _write_csv(path: Path, rows: list[dict[str, Any]], fieldnames: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def write_dataset_audit_outputs(
    *,
    output_dir: Path,
    flat_rows: list[dict[str, Any]],
    summary: dict[str, Any],
) -> dict[str, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    flat_csv = output_dir / "profiles_flat.csv"
    summary_json = output_dir / "summary.json"
    label_csv = output_dir / "counts_by_label.csv"
    approach_csv = output_dir / "counts_by_approach_family.csv"
    range_csv = output_dir / "counts_by_range_band.csv"
    target_zone_csv = output_dir / "counts_by_target_zone_kind.csv"
    spawn_region_csv = output_dir / "counts_by_spawn_region.csv"
    approach_side_csv = output_dir / "counts_by_approach_side.csv"
    approach_lane_csv = output_dir / "counts_by_approach_lane.csv"
    speed_csv = output_dir / "counts_by_u_boat_speed_mps.csv"
    spread_csv = output_dir / "counts_by_spread_deg.csv"

    if flat_rows:
        _write_csv(flat_csv, flat_rows, fieldnames=list(flat_rows[0].keys()))
    else:
        flat_csv.write_text("", encoding="utf-8")

    summary_json.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    _write_csv(label_csv, _count_mapping_rows(summary.get("labels", {})), ["value", "count"])
    _write_csv(approach_csv, _count_mapping_rows(summary.get("approach_families", {})), ["value", "count"])
    _write_csv(range_csv, _count_mapping_rows(summary.get("range_bands", {})), ["value", "count"])
    _write_csv(target_zone_csv, _count_mapping_rows(summary.get("target_zone_kinds", {})), ["value", "count"])
    _write_csv(spawn_region_csv, _count_mapping_rows(summary.get("spawn_regions", {})), ["value", "count"])
    _write_csv(approach_side_csv, _count_mapping_rows(summary.get("approach_sides", {})), ["value", "count"])
    _write_csv(approach_lane_csv, _count_mapping_rows(summary.get("approach_lanes", {})), ["value", "count"])
    _write_csv(speed_csv, _count_mapping_rows(summary.get("u_boat_speed_values_mps", {})), ["value", "count"])
    _write_csv(spread_csv, _count_mapping_rows(summary.get("spread_deg_values", {})), ["value", "count"])
    return {
        "profiles_flat_csv": flat_csv,
        "summary_json": summary_json,
        "counts_by_label_csv": label_csv,
        "counts_by_approach_family_csv": approach_csv,
        "counts_by_range_band_csv": range_csv,
        "counts_by_target_zone_kind_csv": target_zone_csv,
        "counts_by_spawn_region_csv": spawn_region_csv,
        "counts_by_approach_side_csv": approach_side_csv,
        "counts_by_approach_lane_csv": approach_lane_csv,
        "counts_by_u_boat_speed_mps_csv": speed_csv,
        "counts_by_spread_deg_csv": spread_csv,
    }


def main() -> None:
    args = parse_args()
    records = load_dataset_records(args.input)
    flat_rows = flatten_dataset_records(records)
    summary = summarize_flat_rows(flat_rows)
    outputs = write_dataset_audit_outputs(output_dir=args.output_dir, flat_rows=flat_rows, summary=summary)

    print(f"Loaded {summary['profile_count']} profiles from {args.input}")
    print("Label counts:", summary.get("labels", {}))
    print("Approach family counts:", summary.get("approach_families", {}))
    print("Range band counts:", summary.get("range_bands", {}))
    if summary.get("target_zone_kinds"):
        print("Target zone kind counts:", summary.get("target_zone_kinds", {}))
    if summary.get("spawn_regions"):
        print("Spawn region counts:", summary.get("spawn_regions", {}))
    if summary.get("approach_sides"):
        print("Approach side counts:", summary.get("approach_sides", {}))
    print("Top 5 highest-severity profiles:")
    for row in summary.get("top_10_highest_severity", [])[:5]:
        print(
            f"  {row['profile_id']}: severity={row['severity']:.1f}, "
            f"error={row['bearing_error_deg']:.1f}deg, "
            f"{row['approach_family']}/{row['range_band']} [{row['suggested_label']}]"
        )
    for label, path in outputs.items():
        print(f"Wrote {label}: {path}")


if __name__ == "__main__":
    main()
